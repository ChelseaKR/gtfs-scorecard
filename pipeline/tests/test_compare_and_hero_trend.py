"""The static compare table's readings and the hero's trend line.

The compare page's table script is generated by pages_tools and runs in the
browser, so its pure helpers are lifted out of the rendered page and run under
Node, then checked against the Python functions they mirror.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

import pytest

from scorecard_pipeline import pages_tools
from scorecard_pipeline.metrics import resolve_service_horizon_status
from scorecard_pipeline.score import grade_qualifier

ROOT = Path(__file__).resolve().parents[2]


def _function_source(source: str, name: str) -> str:
    start = source.index(f"function {name}(")
    opening = source.index("{", start)
    depth = 0
    for index in range(opening, len(source)):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                return source[start : index + 1]
    raise AssertionError(f"unterminated JavaScript function {name}")


def _run_node(prelude: str, expression: str, cases: list[Any]) -> list[Any]:
    """Evaluate ``expression`` (a function of one case) over every case."""
    node = shutil.which("node")
    assert node is not None
    harness = (
        prelude
        + "\nconst fn = "
        + expression
        + ";\nPromise.all(JSON.parse(process.argv[1]).map((c) => Promise.resolve(fn(c))"
        + ".catch((e) => ({ error: e.message }))))"
        + ".then((out) => process.stdout.write(JSON.stringify(out)));\n"
    )
    completed = subprocess.run(  # noqa: S603 - fixed executable and test-owned inputs
        [node, "-e", harness, json.dumps(cases)],
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(completed.stdout)  # type: ignore[no-any-return]


def _compare_helpers(*names: str) -> str:
    page = pages_tools._render_compare_page([])
    consts = 'var HORIZON_YEARS = 10;\nvar PARTIAL = "partial: freshness not measured";\n'
    return consts + "\n".join(_function_source(page, name) for name in names)


def test_compare_days_left_reads_like_the_status_chip() -> None:
    cases = [
        {"days": None, "horizon": "unknown"},
        {"days": -5, "horizon": "within_review_threshold"},
        {"days": 0, "horizon": "within_review_threshold"},
        {"days": 1, "horizon": "within_review_threshold"},
        {"days": 45, "horizon": "within_review_threshold"},
        {"days": 27000, "horizon": "unusually_distant"},
    ]
    out = _run_node(_compare_helpers("daysText"), "daysText", cases)
    assert out == [
        "—",
        "Expired",
        "Expired",
        "1 day",
        "45 days",
        "Review service end date",
    ]


@pytest.mark.parametrize(
    ("details", "snapshot"),
    [
        ({"service_horizon_status": "unusually_distant", "days_until_expiry": 5}, "2026-11-01"),
        ({"service_horizon_status": "within_review_threshold"}, "2026-11-01"),
        ({"effective_expiry_date": "2099-12-31", "days_until_expiry": 26700}, "2026-11-01"),
        ({"effective_expiry_date": "2036-11-01"}, "2026-11-01"),
        ({"effective_expiry_date": "2036-11-02"}, "2026-11-01"),
        ({"effective_expiry_date": "2034-02-28"}, "2024-02-29"),
        ({"effective_expiry_date": "2034-03-01"}, "2024-02-29"),
        ({"days_until_expiry": 3653}, "2026-11-01"),
        ({"days_until_expiry": 3654}, "2026-11-01"),
        ({"days_until_expiry": 12.5}, "2026-11-01"),
        ({"days_until_expiry": 40}, None),
        ({"days_until_expiry": 40, "snapshot_date": "2026-11-01"}, None),
        ({}, "2026-11-01"),
        ({"effective_expiry_date": "2026-02-30"}, "2026-11-01"),
    ],
)
def test_compare_horizon_status_matches_the_pipeline(
    details: dict[str, Any], snapshot: str | None
) -> None:
    out = _run_node(
        _compare_helpers("isoDate", "horizonStatus"),
        "(c) => horizonStatus(c.details, c.snapshot)",
        [{"details": details, "snapshot": snapshot}],
    )
    assert out == [resolve_service_horizon_status(details, snapshot)]


def test_compare_overall_cell_carries_the_partial_qualifier() -> None:
    partial = {
        "overall": {"grade": "B", "score": 81.2},
        "categories": {"freshness": {"status": "not_measured"}},
    }
    stated = {"overall": {"grade": "C", "score": 74, "grade_qualifier": "partial: x"}}
    full = {
        "overall": {"grade": "A", "score": 93},
        "categories": {"freshness": {"status": "measured"}},
    }
    cases = [partial, stated, full]
    qualifiers = _run_node(_compare_helpers("gradeQualifier"), "gradeQualifier", cases)
    assert qualifiers == [grade_qualifier(c) or "" for c in cases]
    cells = _run_node(_compare_helpers("gradeQualifier", "overallText"), "overallText", cases)
    assert cells == [
        "B (81.2 / 100) · partial: freshness not measured",
        "C (74 / 100) · partial: x",
        "A (93 / 100)",
    ]


def test_compare_load_failure_names_the_agency_not_the_parser() -> None:
    """A 200 HTML page, JSON that is not a scorecard, a 404, and a network
    error all reject with the agency id, which the page quotes back."""
    prelude = (
        "let mode;\n"
        "globalThis.fetch = async () => {\n"
        '  if (mode === "network") throw new TypeError("Failed to fetch");\n'
        '  if (mode === "404") return { ok: false, json: async () => ({}) };\n'
        '  if (mode === "html")\n'
        '    return { ok: true, json: async () => JSON.parse("<!doctype html>") };\n'
        '  if (mode === "shape") return { ok: true, json: async () => ({ hello: 1 }) };\n'
        '  return { ok: true, json: async () => ({ agency: { name: "Demo" }, overall: {} }) };\n'
        "};\n" + _compare_helpers("fetchArtifact")
    )
    out = _run_node(
        prelude,
        "(c) => { mode = c; return fetchArtifact('demo-transit').then((a) => a.agency.name); }",
        ["html", "shape", "404", "network", "ok"],
    )
    assert out == [{"error": "demo-transit"}] * 4 + ["Demo"]


def test_compare_check_dates_leave_no_trace_when_switched_off(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setattr(pages_tools, "COMPARE_SHOWS_CHECK_DATES", False)
    page = pages_tools._render_compare_page([])
    assert "Last checked" not in page
    assert "checked on different days" not in page
    explicit_off = pages_tools._render_compare_page([], show_check_dates=False)
    assert "Last checked" not in explicit_off
    assert "checked on different days" not in explicit_off


def test_compare_check_dates_are_on_by_default() -> None:
    assert pages_tools.COMPARE_SHOWS_CHECK_DATES is True
    page = pages_tools._render_compare_page([])
    assert 'row("Last checked",' in page
    assert (
        '"These scorecards were checked on different days, " +\n'
        '              "so each one counts its days of service left from its own check."'
    ) in page
    # The row sits beside the day count it qualifies.
    assert page.index('row("Last checked",') < page.index('row("Days of service left"')
    # The note only appears when both dates parse and differ.
    assert "if (checkedA && checkedB && checkedA.getTime() !== checkedB.getTime())" in page


# The hero's trend line ------------------------------------------------------


def _point(date: str, score: float, grade: str) -> dict[str, Any]:
    return {"date": date, "score": score, "grade": grade}


@pytest.fixture
def _artifact() -> dict[str, Any]:
    path = ROOT / "data" / "artifacts" / "abq-ride" / "latest.json"
    return json.loads(path.read_text())  # type: ignore[no-any-return]


def test_static_hero_shows_a_letter_move_in_either_direction(
    monkeypatch: pytest.MonkeyPatch, _artifact: dict[str, Any]
) -> None:
    from scorecard_pipeline import render_site

    monkeypatch.setattr(render_site, "_current_rubric_history", lambda history: history)

    fell = render_site._board_hero(
        "Demo",
        "demo",
        _artifact,
        [_point("2026-11-01", 81.0, "B"), _point("2026-11-02", 78.5, "C")],
    )
    assert "down 2.5 since 2026-11-01 &middot; B &rarr; C" in fell

    rose_same = render_site._board_hero(
        "Demo",
        "demo",
        _artifact,
        [_point("2026-11-01", 81.0, "B"), _point("2026-11-02", 82.0, "B")],
    )
    assert "up 1.0 since 2026-11-01" in rose_same
    assert "B &rarr; B" not in rose_same

    rose = render_site._board_hero(
        "Demo",
        "demo",
        _artifact,
        [_point("2026-11-01", 78.0, "C"), _point("2026-11-02", 81.0, "B")],
    )
    assert "up 3.0 since 2026-11-01 &middot; C &rarr; B" in rose


def test_app_hero_shows_a_letter_move_in_either_direction() -> None:
    app = (ROOT / "web" / "src" / "app.js").read_text()
    prelude = (
        "const currentProducerHistory = (h) => h;\n"
        "const formatDate = (d) => d;\n"
        'const esc = (t) => String(t).replace(/</g, "&lt;");\n'
        + _function_source(app, "boardTrend")
    )
    out = _run_node(
        prelude,
        "boardTrend",
        [
            [_point("2026-11-01", 81, "B"), _point("2026-11-02", 78.5, "C")],
            [_point("2026-11-01", 81, "B"), _point("2026-11-02", 82, "B")],
            [_point("2026-11-01", 78, "C"), _point("2026-11-02", 81, "B")],
            [_point("2026-11-01", 81, "B"), _point("2026-11-02", 78, "<i>")],
        ],
    )
    assert out[0].endswith("down 2.5 since 2026-11-01 · B → C")
    assert out[1].endswith("up 1 since 2026-11-01")
    assert out[2].endswith("up 3 since 2026-11-01 · C → B")
    assert "<i>" not in out[3] and "&lt;i>" in out[3]
